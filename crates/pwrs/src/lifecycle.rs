//! Functions that run as a module comes into use in the process and goes
//! out of use.
//!
//! `on_import` runs at every import of the module, in any runspace.
//! `on_remove` runs once for each import: when `Remove-Module` removes
//! it, or when the runspace that imported it closes. `on_load` runs when
//! the module goes from imported in no runspace of the process to
//! imported in one, before that import's `on_import`. `on_unload` runs
//! when it goes back, after the last `on_remove`.
//!
//! A removal unloads nothing: the native library stays mapped and its
//! statics are not reset. So `on_load` runs again when the module is
//! imported after every runspace has removed it, and `on_unload` is
//! where a module releases what `on_load` made, since no destructor
//! runs. A reload of a rebuilt library runs the old copy's `on_unload`
//! and then the new copy's `on_load`.
//!
//! A module's hooks run one at a time, never two at once, so they can
//! share state with no synchronization of their own. No hook runs with a
//! cmdlet or a pipeline. A hook runs on the thread running
//! `Import-Module` or `Remove-Module`, or on the thread closing the
//! runspace. An `Err` from `on_load` or `on_import` fails the import. An
//! `Err` from `on_remove` or `on_unload` is written as an error of the
//! command that ran it, and that command goes ahead; at a runspace's
//! close it goes to standard error.

use crate::PsResult;

/// Generated by `#[on_import]`.
pub trait OnImport: 'static {
    fn run() -> PsResult<()>;
}

/// Generated by `#[on_remove]`.
pub trait OnRemove: 'static {
    fn run() -> PsResult<()>;
}

/// Generated by `#[on_load]`.
pub trait OnLoad: 'static {
    fn run() -> PsResult<()>;
}

/// Generated by `#[on_unload]`.
pub trait OnUnload: 'static {
    fn run() -> PsResult<()>;
}

/// The hooks a module registered through `export_module!`.
pub struct Lifecycle {
    pub on_import: Option<fn() -> PsResult<()>>,
    pub on_remove: Option<fn() -> PsResult<()>>,
    pub on_load: Option<fn() -> PsResult<()>>,
    pub on_unload: Option<fn() -> PsResult<()>>,
}

/// The op `pwrs_module_lifecycle` takes for the import hook.
pub const OP_IMPORT: u32 = 0;
/// The op `pwrs_module_lifecycle` takes for the removal hook.
pub const OP_REMOVE: u32 = 1;
/// The op `pwrs_module_lifecycle` takes for the load hook.
pub const OP_LOAD: u32 = 2;
/// The op `pwrs_module_lifecycle` takes for the unload hook.
pub const OP_UNLOAD: u32 = 3;
